import {cpSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync} from 'node:fs';
import {join, relative} from 'node:path';
import {createHash} from 'node:crypto';

const source = 'frontend';
// A fresh sharing URL for platforms that retain the old root preview.
// Regenerate it on every build so it always opens the latest complete app.
const shareEntry = readFileSync(join(source, 'index.html'), 'utf8')
  .replace('<head>', '<head>\n<base href="/">')
  .replace('rel="canonical" href="https://adolf-kimkim-pwa.onrender.com/"', 'rel="canonical" href="https://adolf-kimkim-pwa.onrender.com/kimkim.html"')
  .replace('property="og:url" content="https://adolf-kimkim-pwa.onrender.com/"', 'property="og:url" content="https://adolf-kimkim-pwa.onrender.com/kimkim.html"');
writeFileSync(join(source, 'kimkim.html'), shareEntry);
function files(dir) {
  return readdirSync(dir, {withFileTypes: true}).flatMap(entry => {
    const path = join(dir, entry.name);
    return entry.isDirectory() ? files(path) : [path];
  });
}
const all = files(source).filter(path => !path.endsWith('/sw.js'));
const digest = createHash('sha256');
// Include cache policy changes in the shell revision, not only frontend files.
digest.update('akk-shell-v2-refresh-assets');
for (const path of all.sort()) digest.update(relative(source, path)).update(readFileSync(path));
const version = digest.digest('hex').slice(0, 12);
const precache = all.map(path => relative(source, path).replaceAll('\\', '/')).filter(path =>
  path === 'offline.html' || path.endsWith('.css') || path === 'manifest.webmanifest' ||
  path.endsWith('.js') || path.startsWith('assets/icons/') || path.startsWith('assets/atmosphere/') || path.startsWith('assets/sounds/') || path.startsWith('assets/sally/') || path.startsWith('assets/story/') ||
  ['assets/kimkim4.png', 'assets/kimkimAI.png', 'assets/kimkimBranding.png'].includes(path));

const worker = `/* Generated by scripts/build.mjs. Change frontend source, then rebuild. */
const CACHE = 'akk-shell-${version}';
const ASSETS = ${JSON.stringify(precache)};
const BASE = new URL('./', self.location.href);
const allowed = new Set(ASSETS.map(path => new URL(path, BASE).pathname));
const badgeStateUrl = new URL('kimkim-badge-state', BASE).href;
async function badge(count) {
  if (count > 0 && self.navigator.setAppBadge) await self.navigator.setAppBadge(count).catch(() => {});
  else if (!count && self.navigator.clearAppBadge) await self.navigator.clearAppBadge().catch(() => {});
}
async function saveBadgeState(state) {
  const cache = await caches.open('kimkim-badge-state');
  await cache.put(badgeStateUrl, new Response(JSON.stringify(state)));
  await badge(state.count);
}
self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(ASSETS.map(path => new Request(new URL(path, BASE).href, {cache: 'reload'})))));
});
self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    for (const name of await caches.keys()) {
      if (name.startsWith('akk-shell-') && name !== CACHE) await caches.delete(name);
    }
    await self.clients.claim();
  })());
});
self.addEventListener('message', event => {
  if (event.data?.type === 'SKIP_WAITING') self.skipWaiting();
  if (event.data?.type === 'KIMKIM_UNREAD_COUNT') {
    const count = Math.max(0, Math.min(99, Number(event.data.count) || 0));
    event.waitUntil(saveBadgeState({count,threads:[]}));
  }
});
self.addEventListener('push', event => {
  event.waitUntil((async () => {
    let payload;
    try { payload = event.data?.json(); } catch { return; }
    const data = payload?.data || payload;
    if (data?.type !== 'kimkim-message' || !/^[a-zA-Z0-9-]{20,80}$/.test(data.messageId || '')) return;
    const clients = await self.clients.matchAll({type:'window',includeUncontrolled:true});
    await Promise.all(clients.map(client => client.postMessage({type:'kimkim-message',threadId:data.threadId,messageId:data.messageId,title:data.title})));
    // A visible page handles its own notice and chime via the Firestore listener.
    if (clients.some(client => client.visibilityState === 'visible')) return;
    // Until a page synchronizes the exact unread count, count each distinct conversation once.
    const cache = await caches.open('kimkim-badge-state');
    const previous = await cache.match(badgeStateUrl);
    const state = previous ? await previous.json().catch(() => ({})) : {};
    const threads = Array.isArray(state.threads) ? state.threads : [];
    const threadId = String(data.threadId || '');
    if (threadId && !threads.includes(threadId)) {
      threads.push(threadId);
      await saveBadgeState({count:Math.min(99, Math.max(0, Number(state.count) || 0) + 1),threads:threads.slice(-99)});
    }
    const url = new URL('./#messages/' + encodeURIComponent(data.threadId || ''), BASE).href;
    await self.registration.showNotification(data.title || 'KimKim', {
      body: data.body || 'Bạn có tin nhắn mới / You have a new message',
      icon: new URL('assets/icons/icon-192.png', BASE).href,
      badge: new URL('assets/icons/icon-192.png', BASE).href,
      tag: 'kimkim-message-' + data.messageId,
      data: {url}, silent: false
    });
  })());
});
self.addEventListener('notificationclick', event => {
  event.notification.close();
  event.waitUntil((async () => {
    const target = event.notification.data?.url;
    if (!target || new URL(target).origin !== BASE.origin) return;
    const clients = await self.clients.matchAll({type:'window',includeUncontrolled:true});
    const page = clients.find(client => client.url.startsWith(BASE.href));
    if (page) { await page.navigate(target); await page.focus(); }
    else await self.clients.openWindow(target);
  })());
});
self.addEventListener('fetch', event => {
  const request = event.request;
  const url = new URL(request.url);
  // Never intercept external Firebase/AI traffic, writes, uploads or API data.
  if (request.method !== 'GET' || url.origin !== BASE.origin) return;
  if (url.pathname.startsWith(new URL('api/', BASE).pathname)) return;
  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).catch(async () => {
      const cache = await caches.open(CACHE);
      return await cache.match(new URL('offline.html', BASE).href) || Response.error();
    }));
    return;
  }
  if (!allowed.has(url.pathname)) return;
  event.respondWith((async () => {
    const cache = await caches.open(CACHE);
    const key = new URL(url.pathname, BASE.origin).href;
    return await cache.match(key) || fetch(request);
  })());
});
`;
writeFileSync(join(source, 'sw.js'), worker);
rmSync('dist', {recursive: true, force: true});
mkdirSync('dist');
cpSync(source, 'dist', {recursive: true});
console.log(`Built ${all.length + 1} files; PWA shell ${version}; ${precache.length} offline assets.`);

