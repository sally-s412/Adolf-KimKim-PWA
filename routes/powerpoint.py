"""PowerPoint generation — converts meeting summary into a downloadable .pptx."""

import io
import logging
from pptx import Presentation
from pptx.util import Inches, Pt, Emu
from pptx.dml.color import RGBColor
from pptx.enum.text import PP_ALIGN

logger = logging.getLogger("powerpoint")

# Brand colors
COLOR_BG = RGBColor(0x0F, 0x17, 0x2A)       # dark navy
COLOR_ACCENT = RGBColor(0x3B, 0x82, 0xF6)    # blue
COLOR_WHITE = RGBColor(0xFF, 0xFF, 0xFF)
COLOR_GRAY = RGBColor(0x94, 0xA3, 0xB8)


def _set_bg(slide, color: RGBColor):
    fill = slide.background.fill
    fill.solid()
    fill.fore_color.rgb = color


def _add_textbox(slide, text: str, left, top, width, height,
                 font_size=18, bold=False, color=COLOR_WHITE, align=PP_ALIGN.LEFT):
    txb = slide.shapes.add_textbox(left, top, width, height)
    tf = txb.text_frame
    tf.word_wrap = True
    p = tf.paragraphs[0]
    p.alignment = align
    run = p.add_run()
    run.text = text
    run.font.size = Pt(font_size)
    run.font.bold = bold
    run.font.color.rgb = color


def generate_pptx(title: str, key_points: list[str], summary: str) -> bytes:
    """Build a minimal .pptx from meeting summary data. Returns raw bytes."""
    prs = Presentation()
    prs.slide_width = Inches(13.33)
    prs.slide_height = Inches(7.5)

    W = prs.slide_width
    H = prs.slide_height
    PAD = Inches(0.6)

    blank_layout = prs.slide_layouts[6]  # completely blank

    # ── Slide 1: Title ──────────────────────────────────────────────
    s1 = prs.slides.add_slide(blank_layout)
    _set_bg(s1, COLOR_BG)

    # accent bar on left
    bar = s1.shapes.add_shape(1, Inches(0), Inches(2.5), Inches(0.08), Inches(2.5))
    bar.fill.solid()
    bar.fill.fore_color.rgb = COLOR_ACCENT
    bar.line.fill.background()

    _add_textbox(s1, "MEETING SUMMARY", PAD, Inches(2.0), W - PAD*2, Inches(0.5),
                 font_size=13, color=COLOR_ACCENT)
    _add_textbox(s1, title, PAD, Inches(2.6), W - PAD*2, Inches(1.8),
                 font_size=36, bold=True, color=COLOR_WHITE)
    _add_textbox(s1, "Generated by Adolf KimKim AI", PAD, Inches(6.5), W - PAD*2, Inches(0.5),
                 font_size=11, color=COLOR_GRAY)

    # ── Slide 2: Key Points ─────────────────────────────────────────
    s2 = prs.slides.add_slide(blank_layout)
    _set_bg(s2, COLOR_BG)

    _add_textbox(s2, "KEY POINTS", PAD, Inches(0.5), W - PAD*2, Inches(0.5),
                 font_size=13, color=COLOR_ACCENT)
    _add_textbox(s2, "Main Topics Discussed", PAD, Inches(0.9), W - PAD*2, Inches(0.7),
                 font_size=28, bold=True, color=COLOR_WHITE)

    # bullet list
    bullet_top = Inches(1.8)
    bullet_h = Inches(0.55)
    for i, kp in enumerate(key_points[:8]):  # cap at 8
        _add_textbox(s2, f"• {kp}", PAD, bullet_top + i * bullet_h,
                     W - PAD*2, bullet_h, font_size=16, color=COLOR_WHITE)

    # ── Slide 3: Summary ────────────────────────────────────────────
    s3 = prs.slides.add_slide(blank_layout)
    _set_bg(s3, COLOR_BG)

    _add_textbox(s3, "SUMMARY", PAD, Inches(0.5), W - PAD*2, Inches(0.5),
                 font_size=13, color=COLOR_ACCENT)
    _add_textbox(s3, "Full Summary", PAD, Inches(0.9), W - PAD*2, Inches(0.7),
                 font_size=28, bold=True, color=COLOR_WHITE)

    # strip markdown headers for cleaner pptx text
    clean = "\n".join(
        ln.lstrip("#").strip() for ln in summary.splitlines()
        if ln.strip() and not ln.strip().startswith("---")
    )
    _add_textbox(s3, clean[:1200], PAD, Inches(1.8), W - PAD*2, Inches(5.2),
                 font_size=13, color=COLOR_GRAY)

    # ── Serialize ───────────────────────────────────────────────────
    buf = io.BytesIO()
    prs.save(buf)
    buf.seek(0)
    logger.info(f"PPTX generated: '{title}', {len(key_points)} key points")
    return buf.read()
