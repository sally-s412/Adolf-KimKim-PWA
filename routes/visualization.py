"""Visualization — renders a meeting summary as a styled PNG image using Pillow."""

import io
import logging
import textwrap
from PIL import Image, ImageDraw, ImageFont

logger = logging.getLogger("visualization")

# Canvas
W, H = 1280, 720

# Colors (RGB)
C_BG      = (15, 23, 42)        # dark navy
C_CARD    = (30, 41, 59)        # card bg
C_ACCENT  = (59, 130, 246)      # blue
C_WHITE   = (226, 232, 240)
C_GRAY    = (100, 116, 139)
C_GREEN   = (34, 197, 94)

FONT_PATHS = [
    "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
    "/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf",
    "/usr/share/fonts/truetype/freefont/FreeSansBold.ttf",
    "/usr/share/fonts/TTF/DejaVuSans-Bold.ttf",
]
FONT_PATHS_REG = [p.replace("Bold", "").replace("-Bold", "") for p in FONT_PATHS]


def _load_font(size: int, bold=False) -> ImageFont.ImageFont:
    paths = FONT_PATHS if bold else FONT_PATHS_REG
    for p in paths:
        try:
            return ImageFont.truetype(p, size)
        except Exception:
            continue
    return ImageFont.load_default()


def generate_image(title: str, key_points: list[str], summary: str) -> bytes:
    """Render a summary card as a 1280×720 PNG. Returns raw bytes."""
    img = Image.new("RGB", (W, H), C_BG)
    d = ImageDraw.Draw(img)

    # ── accent bar top ───────────────────────────────────────────
    d.rectangle([0, 0, W, 5], fill=C_ACCENT)

    # ── header ───────────────────────────────────────────────────
    f_label = _load_font(13)
    f_title = _load_font(32, bold=True)
    f_body  = _load_font(15)
    f_kp    = _load_font(14)

    d.text((40, 24), "MEETING SUMMARY  •  Adolf KimKim AI", font=f_label, fill=C_ACCENT)
    # title (wrap if long)
    title_lines = textwrap.wrap(title, width=52)
    ty = 56
    for line in title_lines[:2]:
        d.text((40, ty), line, font=f_title, fill=C_WHITE)
        ty += 42

    # divider
    d.rectangle([40, ty + 10, W - 40, ty + 12], fill=C_ACCENT)
    ty += 26

    # ── left column: key points ───────────────────────────────────
    col_split = 480
    d.text((40, ty), "KEY POINTS", font=f_label, fill=C_ACCENT)
    ty_kp = ty + 22
    for kp in key_points[:7]:
        wrapped = textwrap.wrap(f"• {kp}", width=34)
        for ln in wrapped[:2]:
            d.text((40, ty_kp), ln, font=f_kp, fill=C_WHITE)
            ty_kp += 22
        ty_kp += 4

    # ── right column: summary excerpt ─────────────────────────────
    d.text((col_split, ty), "SUMMARY", font=f_label, fill=C_ACCENT)
    ty_sum = ty + 22

    # strip markdown syntax for clean display
    clean_lines = []
    for ln in summary.splitlines():
        stripped = ln.lstrip("#").strip()
        if stripped and not stripped.startswith("---"):
            clean_lines.append(stripped)

    excerpt = " ".join(clean_lines)[:600]
    wrapped_sum = textwrap.wrap(excerpt, width=52)
    for ln in wrapped_sum[:16]:
        d.text((col_split, ty_sum), ln, font=f_body, fill=C_GRAY)
        ty_sum += 22

    # ── footer bar ───────────────────────────────────────────────
    d.rectangle([0, H - 36, W, H], fill=C_CARD)
    d.text((40, H - 24), "Generated by Adolf KimKim  •  AI Meeting Intelligence", font=f_label, fill=C_GRAY)

    # ── serialize ────────────────────────────────────────────────
    buf = io.BytesIO()
    img.save(buf, format="PNG")
    buf.seek(0)
    logger.info(f"Visualization PNG generated: '{title}'")
    return buf.read()
